import { useCallback, useEffect, useState } from "react"
import { Link, useParams } from "react-router-dom"
import { Check, AlertCircle, AlertTriangle, RefreshCw, Home } from "lucide-react"
import { Button } from "@/components/ui/button"
import { verifyAttendancePdf, type VerifyResult } from "@/lib/registerPdf/verifyPdf"

function formatBlantyre(iso: string): string {
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return iso
  return date.toLocaleString(undefined, {
    timeZone: "Africa/Blantyre",
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  })
}

type VerifyStatus = "loading" | "verified" | "not_found" | "error"

/**
 * Status band at the top of the card. Built from plain flex elements (not the
 * shadcn Card parts) so the band sits flush with the card edge and everything
 * is centred on one axis: Card/CardHeader add their own padding, gap and grid
 * layout, which pushed the band down and stretched the icon badge.
 */
function StatusBand({
  className,
  icon,
  title,
  description,
}: {
  className: string
  icon: React.ReactNode
  title: string
  description?: string
}) {
  return (
    <div className={`flex flex-col items-center gap-3 px-6 py-8 text-center text-white ${className}`}>
      <div className="flex size-14 shrink-0 items-center justify-center rounded-full bg-white">
        {icon}
      </div>
      <h1 className="text-2xl font-bold tracking-tight text-balance">{title}</h1>
      {description && (
        <p className="max-w-xs text-sm text-pretty text-white/90">{description}</p>
      )}
    </div>
  )
}

export default function VerifyPdf() {
  const { code } = useParams()
  const [status, setStatus] = useState<VerifyStatus>("loading")
  const [result, setResult] = useState<VerifyResult | null>(null)
  const [retrying, setRetrying] = useState(false)

  const check = useCallback(
    async (codeValue: string | undefined): Promise<VerifyResult | null> => {
      if (!codeValue) return null
      return verifyAttendancePdf(codeValue)
    },
    []
  )

  const handleRetry = () => {
    setRetrying(true)
    void (async () => {
      try {
        const result = await check(code)
        setResult(result ?? null)
        setStatus(result ? result.status : "not_found")
      } catch {
        setStatus("error")
      } finally {
        setRetrying(false)
      }
    })()
  }

  // Kick off the check on mount / code change.
  useEffect(() => {
    let cancelled = false
    void (async () => {
      try {
        const result = await check(code)
        if (!cancelled) {
          setResult(result ?? null)
          setStatus(result ? result.status : "not_found")
        }
      } catch {
        if (!cancelled) setStatus("error")
      }
    })()
    return () => {
      cancelled = true
    }
  }, [code, check])

  const codeDisplay = code ? code.toUpperCase() : ""

  return (
    <div className="flex min-h-dvh items-center justify-center bg-muted/40 px-4 py-10">
      <main className="flex w-full max-w-md flex-col overflow-hidden rounded-3xl border border-border/60 bg-card text-card-foreground shadow-sm">
        {status === "loading" ? (
          <div className="flex flex-col items-center gap-3 px-6 py-12" aria-busy="true">
            <div className="size-14 animate-pulse rounded-full bg-muted" />
            <div className="h-4 w-1/3 animate-pulse rounded-full bg-muted" />
            <div className="h-4 w-1/2 animate-pulse rounded-full bg-muted" />
          </div>
        ) : status === "verified" ? (
          <>
            <StatusBand
              className="bg-emerald-600"
              icon={<Check className="size-7 text-emerald-600" strokeWidth={3} aria-hidden="true" />}
              title="Verified document"
              description="This register was generated by Class-BARS."
            />
            <div className="flex flex-col items-center gap-3 px-6 py-6 text-center">
              <p className="flex flex-wrap items-center justify-center gap-2 text-sm text-muted-foreground">
                <span>Verification code</span>
                <span className="rounded-md bg-emerald-600/10 px-2 py-0.5 font-mono font-semibold text-emerald-700 dark:text-emerald-400">
                  {codeDisplay}
                </span>
              </p>
              {result && result.status === "verified" && result.courseCode && (
                <p className="text-lg font-semibold text-balance break-words">
                  {result.courseCode}
                  {result.courseName ? ` — ${result.courseName}` : ""}
                </p>
              )}
              {result && result.status === "verified" && result.createdAt && (
                <p className="text-xs text-muted-foreground">
                  Generated {formatBlantyre(result.createdAt)} (Blantyre/Mw)
                </p>
              )}
              <p className="max-w-sm text-xs text-pretty text-muted-foreground">
                This confirms the code was issued by Class-BARS. Check that the course and date
                match the document you hold; if they differ, treat the document as invalid.
              </p>
            </div>
          </>
        ) : status === "not_found" ? (
          <>
            <StatusBand
              className="bg-red-600"
              icon={<AlertTriangle className="size-7 text-red-600" strokeWidth={2.5} aria-hidden="true" />}
              title="Could not verify this document"
              description="This code was not found. The document may not have been generated by Class-BARS, so do not rely on it."
            />
            <div className="flex flex-col items-center gap-3 px-6 py-6 text-center">
              <p className="max-w-sm text-xs text-pretty text-muted-foreground">
                Contact the lecturer or the university to confirm the document is genuine before
                relying on it.
              </p>
              <Button
                onClick={() => void handleRetry()}
                className="h-10 rounded-full bg-red-600 px-5 text-white hover:bg-red-700"
              >
                Try another code
              </Button>
            </div>
          </>
        ) : (
          // error
          <>
            {/* Neutral amber band: no verdict, just a temporary problem */}
            <StatusBand
              className="bg-amber-500"
              icon={<AlertCircle className="size-7 text-amber-600" strokeWidth={2.5} aria-hidden="true" />}
              title="We could not check this right now"
              description="Try again in a moment."
            />
            <div className="flex flex-col items-center gap-3 px-6 py-6 text-center">
              <Button
                onClick={() => void handleRetry()}
                disabled={retrying}
                className="h-10 min-w-24 rounded-full px-5"
              >
                {retrying ? (
                  <RefreshCw className="size-4 animate-spin" aria-hidden="true" />
                ) : (
                  "Retry"
                )}
              </Button>
            </div>
          </>
        )}
        <div className="border-t border-border/60 p-4">
          <Link
            to="/"
            className="flex h-10 w-full items-center justify-center gap-2 rounded-full border border-border text-sm text-muted-foreground transition-colors hover:bg-muted"
          >
            <Home className="size-4" aria-hidden="true" />
            Back to home
          </Link>
        </div>
      </main>
    </div>
  )
}